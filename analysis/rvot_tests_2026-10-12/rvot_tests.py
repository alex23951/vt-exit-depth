def patched_purkinje():
    """14_purkinje.py with build()'s allowed endocardium split into LV septum / LV free wall / RV septum / RV free
    wall limits (defaults = v3). Written to this folder; the original file is not touched."""
    src = open(os.path.join(B, '14_purkinje.py')).read()
    old = ("    lv_ok = lv[z[lv] <= P['z_max']]\n"
           "    rv_ok = np.union1d(rv_fw[z[rv_fw] <= P['z_max']], rv_sep[z[rv_sep] <= P['rv_septum_z_max']])\n")
    new = ("    lv_sep_ = lv[cKDTree(pts[rv]).query(pts[lv])[0] < t_epi.query(pts[lv])[0]]   # rvot_tests 2026-10-12\n"
           "    lv_ok = np.union1d(lv[z[lv] <= P['z_max']], lv_sep_[z[lv_sep_] <= P.get('lv_septum_z_max', P['z_max'])])\n"
           "    rv_ok = np.union1d(rv_fw[z[rv_fw] <= P.get('rv_fw_z_max', P['z_max'])], rv_sep[z[rv_sep] <= P['rv_septum_z_max']])\n")
    assert src.count(old) == 1
    f = os.path.join(HERE, 'purkinje_variant.py')
    open(f, 'w').write('# GENERATED by rvot_tests.py from sims/biv_model/14_purkinje.py (only build()\'s allowed-endocardium\n'
                       '# lines changed); exploratory, 12 Oct 2026. Do not use for study runs.\n' + src.replace(old, new))
    spec = importlib.util.spec_from_file_location('purkinje_variant', f)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


